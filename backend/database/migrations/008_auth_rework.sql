-- Auth rework.
--
-- 1. Column names -> snake_case. Unquoted identifiers fold to lowercase in
--    Postgres, so `FirstName` was really `firstname` and every Record["FirstName"]
--    lookup raised KeyError. Renaming explicitly kills that whole class of bug.
-- 2. Login codes move to their own table. They cannot live on `users`: a code is
--    requested BEFORE we know whether the person has an account, and creating a
--    user row on request would let anyone mint rows (and enumerate members) by
--    typing an email. The code row also needs its own attempt counter and
--    single-use marker.
-- 3. Names become nullable — an external signup only proves an email address.

ALTER TABLE public.users RENAME COLUMN firstname TO first_name;
ALTER TABLE public.users RENAME COLUMN surname   TO last_name;
ALTER TABLE public.users RENAME COLUMN member    TO member_id;

ALTER TABLE public.users ALTER COLUMN first_name DROP NOT NULL;
ALTER TABLE public.users ALTER COLUMN last_name  DROP NOT NULL;

ALTER TABLE public.users DROP COLUMN IF EXISTS login_code;
ALTER TABLE public.users DROP COLUMN IF EXISTS login_expiry;

ALTER TABLE public.users ADD COLUMN IF NOT EXISTS created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ;

-- Emails are matched case-insensitively everywhere; enforce that in the index
-- rather than trusting every call site to lower() first.
-- Dropping the constraint drops its backing index; DROP INDEX first would fail.
ALTER TABLE public.users DROP CONSTRAINT IF EXISTS users_email_key;
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_key ON public.users (lower(email));

CREATE TABLE IF NOT EXISTS public.login_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR     NOT NULL,
    code_hash   CHAR(64)    NOT NULL,      -- sha256 hex; the code itself is emailed
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at  TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    attempts    SMALLINT    NOT NULL DEFAULT 0,
    request_ip  VARCHAR
);

-- Verification looks up the newest live code for an email.
CREATE INDEX IF NOT EXISTS login_codes_email_idx
    ON public.login_codes (lower(email), created_at DESC);

-- Sessions: timestamps become timezone-aware so expiry comparisons survive BST.
ALTER TABLE public.sessions ALTER COLUMN created_at   TYPE TIMESTAMPTZ USING created_at   AT TIME ZONE 'UTC';
ALTER TABLE public.sessions ALTER COLUMN last_seen_at TYPE TIMESTAMPTZ USING last_seen_at AT TIME ZONE 'UTC';
ALTER TABLE public.sessions ALTER COLUMN expires_at   TYPE TIMESTAMPTZ USING expires_at   AT TIME ZONE 'UTC';

ALTER TABLE public.sessions DROP CONSTRAINT IF EXISTS sessions_user_id_fkey;
ALTER TABLE public.sessions
    ADD CONSTRAINT sessions_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS sessions_expires_at_idx ON public.sessions (expires_at);
CREATE INDEX IF NOT EXISTS sessions_user_id_idx    ON public.sessions (user_id);
