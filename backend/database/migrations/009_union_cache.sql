-- Local mirror of eActivities data.
--
-- The eActivities API is explicitly rate limited ("excessive requests" earns a
-- 5 minute IP ban, repeated auth failures an hour) and online sales only refresh
-- at 06:00 daily. So nothing in a request path may call it directly: we sync
-- into these tables and every read serves from here.
--
-- Academic year is the eActivities `xx-xx` string (e.g. '26-27').

-- `members` already exists (migration 003) as the ICU membership mirror.
-- Extend it into a proper synced table keyed on CID.
ALTER TABLE public.members RENAME COLUMN firstname TO first_name;
ALTER TABLE public.members RENAME COLUMN surname   TO last_name;

ALTER TABLE public.members ADD COLUMN IF NOT EXISTS order_no      VARCHAR;
ALTER TABLE public.members ADD COLUMN IF NOT EXISTS member_type   VARCHAR;
ALTER TABLE public.members ADD COLUMN IF NOT EXISTS academic_year VARCHAR;
ALTER TABLE public.members ADD COLUMN IF NOT EXISTS synced_at     TIMESTAMPTZ NOT NULL DEFAULT NOW();

-- One row per person. `academic_year` records the most recent year in which ICU
-- reported them as a member, which is how membership expiry is evaluated: a user
-- is a current member only if this equals the current academic year.
CREATE UNIQUE INDEX IF NOT EXISTS members_cid_key ON public.members (cid);
CREATE INDEX IF NOT EXISTS members_email_lower_idx ON public.members (lower(email));
CREATE INDEX IF NOT EXISTS members_login_lower_idx ON public.members (lower(login));

-- Committee, straight from /reports/committee. Names and roles are ICU's; the
-- editorial overlay (intro text, photo) lives in committee_profiles.
CREATE TABLE IF NOT EXISTS public.committee (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cid           VARCHAR     NOT NULL,
    first_name    VARCHAR,
    last_name     VARCHAR,
    email         VARCHAR,
    login         VARCHAR,
    post_name     VARCHAR     NOT NULL,
    phone_no      VARCHAR,
    start_date    TIMESTAMPTZ,
    end_date      TIMESTAMPTZ,
    academic_year VARCHAR     NOT NULL,
    synced_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (cid, post_name, academic_year)
);

-- Products and their lines, from /reports/products (NOT /products — only the
-- reports endpoint is populated for our centre).
CREATE TABLE IF NOT EXISTS public.union_products (
    product_id         BIGINT      NOT NULL,
    product_line_id    BIGINT      NOT NULL,
    academic_year      VARCHAR     NOT NULL,
    product_name       VARCHAR,
    line_name          VARCHAR,
    description        VARCHAR,
    price              NUMERIC(10,2),
    active             BOOLEAN,
    selling_date_start TIMESTAMPTZ,
    selling_date_end   TIMESTAMPTZ,
    url                VARCHAR,
    synced_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- ProductLineID is not documented as globally unique, so the pair is the key.
    PRIMARY KEY (product_id, product_line_id, academic_year)
);

-- Online sales. This is the evidence that a reservation was actually paid for.
-- OrderNumber is a VARCHAR: real order numbers contain letters.
CREATE TABLE IF NOT EXISTS public.union_sales (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number       VARCHAR     NOT NULL,
    academic_year      VARCHAR     NOT NULL,
    sale_datetime      TIMESTAMPTZ,
    product_id         BIGINT      NOT NULL,
    product_line_id    BIGINT      NOT NULL,
    price              NUMERIC(10,2),
    quantity           INTEGER     NOT NULL DEFAULT 1,
    quantity_collected INTEGER     NOT NULL DEFAULT 0,
    customer_cid       VARCHAR,
    customer_first_name VARCHAR,
    customer_last_name  VARCHAR,
    customer_email     VARCHAR,
    customer_login     VARCHAR,
    synced_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- A sale is identified by order + line. Re-syncing the same day must not
    -- duplicate rows, so this drives an ON CONFLICT upsert.
    UNIQUE (order_number, product_id, product_line_id)
);

CREATE INDEX IF NOT EXISTS union_sales_login_idx ON public.union_sales (lower(customer_login));
CREATE INDEX IF NOT EXISTS union_sales_cid_idx   ON public.union_sales (customer_cid);
CREATE INDEX IF NOT EXISTS union_sales_order_idx ON public.union_sales (upper(order_number));
CREATE INDEX IF NOT EXISTS union_sales_product_idx
    ON public.union_sales (product_id, product_line_id);

-- Audit of sync runs, so the admin screen can show "last synced" and failures
-- are visible rather than silent.
CREATE TABLE IF NOT EXISTS public.union_sync_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          VARCHAR     NOT NULL,   -- members | committee | products | sales
    academic_year VARCHAR,
    started_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at   TIMESTAMPTZ,
    ok            BOOLEAN,
    row_count     INTEGER,
    message       VARCHAR
);

CREATE INDEX IF NOT EXISTS union_sync_runs_kind_idx
    ON public.union_sync_runs (kind, started_at DESC);
