-- Events, ticket types and reservations.
--
-- Booking is reservation-style because payment happens off-site on the Union
-- shop and online sales only appear in the eActivities feed the next morning at
-- 06:00. So a booking is a HOLD that survives at least one sync cycle, and is
-- promoted to CONFIRMED once a matching sale turns up:
--
--   held ──(matching union sale found)──> confirmed
--     │
--     ├──(hold window elapses)──> expired
--     └──(user or admin cancels)─> cancelled
--
-- Members are matched automatically on their ICU login/CID. External users
-- (users.member_id IS NULL) have no ICU identity in the sales feed, so they type
-- their order number in and we match on that.

CREATE TABLE IF NOT EXISTS public.events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug          VARCHAR     NOT NULL UNIQUE,
    title         VARCHAR     NOT NULL,
    category      VARCHAR,
    description   TEXT        NOT NULL DEFAULT '',
    image_url     VARCHAR,
    venue         VARCHAR,
    starts_at     TIMESTAMPTZ NOT NULL,
    ends_at       TIMESTAMPTZ,
    -- NULL = no event-wide cap (per-type caps may still apply). Both can be set:
    -- "200 tickets total, of which at most 120 with alcohol".
    capacity      INTEGER     CHECK (capacity IS NULL OR capacity > 0),
    -- How long a hold survives without a matching sale. Must clear at least one
    -- 06:00 sync, so anything under 24h would expire bookings that were paid for.
    hold_hours    INTEGER     NOT NULL DEFAULT 72 CHECK (hold_hours >= 24),
    published     BOOLEAN     NOT NULL DEFAULT false,
    academic_year VARCHAR     NOT NULL,
    created_by    BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS events_starts_at_idx ON public.events (starts_at DESC);
CREATE INDEX IF NOT EXISTS events_published_idx ON public.events (published, starts_at DESC);

CREATE TABLE IF NOT EXISTS public.ticket_types (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      BIGINT      NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    name          VARCHAR     NOT NULL,           -- e.g. 'Alcohol', 'No alcohol'
    description   VARCHAR,
    price_pence   INTEGER     NOT NULL DEFAULT 0 CHECK (price_pence >= 0),
    capacity      INTEGER     CHECK (capacity IS NULL OR capacity > 0),
    -- Some tickets are free/at-the-door and need no Union purchase to confirm.
    requires_purchase BOOLEAN NOT NULL DEFAULT true,
    members_only  BOOLEAN     NOT NULL DEFAULT false,
    max_per_user  INTEGER     NOT NULL DEFAULT 1 CHECK (max_per_user > 0),
    sort_order    INTEGER     NOT NULL DEFAULT 100,
    UNIQUE (event_id, name)
);

CREATE INDEX IF NOT EXISTS ticket_types_event_idx ON public.ticket_types (event_id, sort_order);

-- Admin-managed mapping from a Union product/line to the thing it pays for.
-- `product_line_id` NULL means "any line of this product", which is the safe
-- default given ProductLineID uniqueness is not guaranteed across products.
CREATE TABLE IF NOT EXISTS public.product_links (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose         VARCHAR NOT NULL CHECK (purpose IN ('event_ticket', 'locker', 'membership')),
    event_id        BIGINT  REFERENCES public.events(id) ON DELETE CASCADE,
    ticket_type_id  BIGINT  REFERENCES public.ticket_types(id) ON DELETE CASCADE,
    union_product_id      BIGINT NOT NULL,
    union_product_line_id BIGINT,
    academic_year   VARCHAR NOT NULL,
    created_by      BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- An event_ticket link must point at something; locker/membership must not.
    CHECK (
        (purpose = 'event_ticket' AND (event_id IS NOT NULL OR ticket_type_id IS NOT NULL))
        OR (purpose <> 'event_ticket' AND event_id IS NULL AND ticket_type_id IS NULL)
    )
);

-- Same product mapped twice to the same target is a config error, not a merge.
CREATE UNIQUE INDEX IF NOT EXISTS product_links_ticket_key
    ON public.product_links (ticket_type_id, union_product_id, COALESCE(union_product_line_id, -1))
    WHERE ticket_type_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS product_links_purpose_key
    ON public.product_links (purpose, union_product_id, COALESCE(union_product_line_id, -1), academic_year)
    WHERE ticket_type_id IS NULL;

CREATE TABLE IF NOT EXISTS public.reservations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       BIGINT      NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    ticket_type_id BIGINT      NOT NULL REFERENCES public.ticket_types(id) ON DELETE CASCADE,
    user_id        BIGINT      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    quantity       INTEGER     NOT NULL DEFAULT 1 CHECK (quantity > 0),
    status         VARCHAR     NOT NULL DEFAULT 'held'
                   CHECK (status IN ('held', 'confirmed', 'cancelled', 'expired')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at     TIMESTAMPTZ NOT NULL,
    confirmed_at   TIMESTAMPTZ,
    cancelled_at   TIMESTAMPTZ,
    -- Supplied by external users; members are matched on their ICU login.
    order_number   VARCHAR,
    matched_sale_id BIGINT     REFERENCES public.union_sales(id) ON DELETE SET NULL,
    note           VARCHAR
);

-- Counting live demand is the hot path for every capacity check, and it is what
-- the partial index is for: only held-and-unexpired or confirmed rows consume
-- stock.
CREATE INDEX IF NOT EXISTS reservations_live_idx
    ON public.reservations (event_id, ticket_type_id)
    WHERE status IN ('held', 'confirmed');

CREATE INDEX IF NOT EXISTS reservations_user_idx ON public.reservations (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS reservations_expiry_idx
    ON public.reservations (expires_at) WHERE status = 'held';

-- One sale pays for one reservation. Without this, a single order number could
-- be typed in by several external users and confirm all of them.
CREATE UNIQUE INDEX IF NOT EXISTS reservations_sale_key
    ON public.reservations (matched_sale_id)
    WHERE matched_sale_id IS NOT NULL;
