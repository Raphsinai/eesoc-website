-- Lockers.
--
-- Replaces the placeholder table from migration 005, which modelled a booking as
-- columns on the locker itself with `BookedBy NOT NULL` — that made a free
-- locker unrepresentable and lost history on release. Bookings are now their own
-- rows, so a locker can be free, and last year's occupants stay on record.
--
-- Lockers are members-only AND require a locker purchase on the Union shop. A
-- member may buy more than one, so entitlement is "active bookings < purchased
-- quantity" rather than a boolean.

DROP TABLE IF EXISTS public.lockers;

CREATE TABLE IF NOT EXISTS public.lockers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank       VARCHAR(4)  NOT NULL,          -- 'A', 'B', ... matches the UI's bank letter
    number     INTEGER     NOT NULL,
    floor      INTEGER,
    is_active  BOOLEAN     NOT NULL DEFAULT true,  -- false = broken/withdrawn
    note       VARCHAR,
    UNIQUE (bank, number)
);

CREATE TABLE IF NOT EXISTS public.locker_bookings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locker_id      BIGINT      NOT NULL REFERENCES public.lockers(id) ON DELETE CASCADE,
    user_id        BIGINT      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    academic_year  VARCHAR     NOT NULL,
    order_number   VARCHAR,
    matched_sale_id BIGINT     REFERENCES public.union_sales(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    released_at    TIMESTAMPTZ
);

-- The oversell guard: at most one live booking per locker. This is a database
-- constraint rather than an application check, so two simultaneous requests for
-- the same locker cannot both succeed — the loser gets a unique violation.
CREATE UNIQUE INDEX IF NOT EXISTS locker_bookings_active_key
    ON public.locker_bookings (locker_id)
    WHERE released_at IS NULL;

-- One purchase pays for one locker.
CREATE UNIQUE INDEX IF NOT EXISTS locker_bookings_sale_key
    ON public.locker_bookings (matched_sale_id)
    WHERE matched_sale_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS locker_bookings_user_idx
    ON public.locker_bookings (user_id) WHERE released_at IS NULL;

-- Seed the physical banks so the map renders before anyone books.
INSERT INTO public.lockers (bank, number, floor)
SELECT bank, n, 4
FROM (VALUES ('A'), ('B'), ('C'), ('D')) AS banks(bank),
     generate_series(1, 12) AS n
ON CONFLICT (bank, number) DO NOTHING;
