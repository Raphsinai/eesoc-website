-- Sponsors and the sponsor portal.
--
-- API.md gates /portal on role "sponsor", but nothing backed that role: there
-- was no sponsor table and no way for a sponsor to hold an account. A sponsor
-- account is an ordinary user (same email-code login) linked to a sponsor org.

CREATE TABLE IF NOT EXISTS public.sponsors (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR     NOT NULL UNIQUE,
    name       VARCHAR     NOT NULL,
    tier       VARCHAR,                       -- 'Package sponsor', 'Talks partner', ...
    strand     VARCHAR,                       -- 'Workshops · Hackathon'
    one_line   VARCHAR,
    blurb      TEXT        NOT NULL DEFAULT '',
    with_us    TEXT[]      NOT NULL DEFAULT '{}',
    site       VARCHAR,
    logo_url   VARCHAR,
    roles      INTEGER     NOT NULL DEFAULT 0,
    active     BOOLEAN     NOT NULL DEFAULT true,
    sort_order INTEGER     NOT NULL DEFAULT 100,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Which accounts may act for which sponsor. A person could in principle
-- represent two sponsors, so this is a join table rather than a column on users.
CREATE TABLE IF NOT EXISTS public.sponsor_users (
    user_id    BIGINT      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    sponsor_id BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, sponsor_id)
);

CREATE TABLE IF NOT EXISTS public.job_listings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id  BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    title       VARCHAR     NOT NULL,
    location    VARCHAR,
    body        TEXT        NOT NULL DEFAULT '',
    apply_url   VARCHAR,
    closes_on   DATE,
    applications INTEGER    NOT NULL DEFAULT 0,
    status      VARCHAR     NOT NULL DEFAULT 'live'
                CHECK (status IN ('draft', 'live', 'closed')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS job_listings_sponsor_idx
    ON public.job_listings (sponsor_id, created_at DESC);

-- A sponsor claiming a slot on an event. Claims are requests until an admin
-- confirms, which is why the status is not just a boolean.
CREATE TABLE IF NOT EXISTS public.event_sponsorships (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   BIGINT      NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    sponsor_id BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    status     VARCHAR     NOT NULL DEFAULT 'claimed'
               CHECK (status IN ('claimed', 'confirmed', 'declined')),
    note       VARCHAR,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (event_id, sponsor_id)
);

CREATE TABLE IF NOT EXISTS public.sponsor_requests (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    format     VARCHAR,                       -- 'Sponsored workshop', 'Site visit', ...
    body       TEXT        NOT NULL DEFAULT '',
    status     VARCHAR     NOT NULL DEFAULT 'open'
               CHECK (status IN ('open', 'in_progress', 'closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sponsor_assets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id  BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    label       VARCHAR     NOT NULL,
    file_url    VARCHAR     NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- CV book is an opt-in by the member, surfaced to package sponsors.
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS cv_opt_in BOOLEAN NOT NULL DEFAULT false;
