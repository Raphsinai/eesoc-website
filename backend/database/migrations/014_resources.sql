-- Resources.
--
-- Modelled as a tree rather than the fixed "categories of cards or a table"
-- shape the mockup assumed, because the real eesoc.com content is nested three
-- deep: page -> section -> module -> per-year feedback. A self-referencing
-- parent_id handles any depth, so adding a level never needs a migration.
--
-- Everything is editable: an admin adds, edits, reorders or removes a node
-- without a deploy.

CREATE TABLE IF NOT EXISTS public.resource_pages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR     NOT NULL UNIQUE,
    title       VARCHAR     NOT NULL,
    -- Per-page SEO. eesoc.com reuses one site-wide description on every page,
    -- which wastes the snippet; this lets each page describe itself.
    description VARCHAR,
    intro       TEXT        NOT NULL DEFAULT '',
    icon        VARCHAR,
    sort_order  INTEGER     NOT NULL DEFAULT 100,
    published   BOOLEAN     NOT NULL DEFAULT true,
    members_only BOOLEAN    NOT NULL DEFAULT false,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by  BIGINT      REFERENCES public.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS resource_pages_order_idx
    ON public.resource_pages (sort_order, title);

CREATE TABLE IF NOT EXISTS public.resource_entries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id    BIGINT      NOT NULL REFERENCES public.resource_pages(id) ON DELETE CASCADE,
    -- Self-reference gives the tree its depth. ON DELETE CASCADE means removing
    -- a module takes its year entries with it, which is what "remove element"
    -- should mean to whoever presses the button.
    parent_id  BIGINT      REFERENCES public.resource_entries(id) ON DELETE CASCADE,
    kind       VARCHAR     NOT NULL DEFAULT 'item'
               CHECK (kind IN ('section', 'item', 'year', 'link', 'note', 'file')),
    title      VARCHAR     NOT NULL,
    body       TEXT        NOT NULL DEFAULT '',   -- markdown
    url        VARCHAR,
    badge      VARCHAR,
    sort_order INTEGER     NOT NULL DEFAULT 100,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS resource_entries_page_idx
    ON public.resource_entries (page_id, parent_id, sort_order);

-- Uploaded files (committee photos, event images, sponsor logos, resource PDFs).
-- Only metadata lives here; the bytes go on a mounted volume, because a
-- container filesystem is thrown away on every deploy and Postgres is the wrong
-- place for binaries.
CREATE TABLE IF NOT EXISTS public.uploads (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stored_name  VARCHAR     NOT NULL UNIQUE,   -- random name on disk
    original_name VARCHAR    NOT NULL,
    content_type VARCHAR     NOT NULL,
    byte_size    BIGINT      NOT NULL,
    purpose      VARCHAR     NOT NULL DEFAULT 'general',
    uploaded_by  BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    uploaded_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS uploads_purpose_idx ON public.uploads (purpose, uploaded_at DESC);
