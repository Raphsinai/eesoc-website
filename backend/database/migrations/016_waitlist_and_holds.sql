-- Waitlists, two-phase holds, and sponsor tidy-up.

-- ---------------------------------------------------------------- holds ----
-- A guest reserves the slot BEFORE filling the form, so the seat cannot be sold
-- from under them while they type. That first hold is a `draft`: short-lived,
-- and not yet owned by anybody.
ALTER TABLE public.reservations ALTER COLUMN user_id DROP NOT NULL;

ALTER TABLE public.reservations DROP CONSTRAINT IF EXISTS reservations_status_check;
ALTER TABLE public.reservations
    ADD CONSTRAINT reservations_status_check
    CHECK (status IN ('draft', 'held', 'confirmed', 'cancelled', 'expired'));

-- A draft with no owner is only meaningful while it is unexpired; an owned row
-- must always have a user.
ALTER TABLE public.reservations
    ADD CONSTRAINT reservations_owner_check
    CHECK (status = 'draft' OR user_id IS NOT NULL);

-- Opaque handle returned to an anonymous browser so it can convert its own
-- draft and nobody else's — the row id alone would be guessable.
ALTER TABLE public.reservations ADD COLUMN IF NOT EXISTS draft_token CHAR(64);
CREATE UNIQUE INDEX IF NOT EXISTS reservations_draft_token_key
    ON public.reservations (draft_token) WHERE draft_token IS NOT NULL;

-- Two days to buy on the Union shop, matching the copy on eesoc.com.
ALTER TABLE public.events ALTER COLUMN hold_hours SET DEFAULT 48;
ALTER TABLE public.events DROP CONSTRAINT IF EXISTS events_hold_hours_check;
ALTER TABLE public.events
    ADD CONSTRAINT events_hold_hours_check CHECK (hold_hours >= 1);

-- ------------------------------------------------------------- waitlist ----
-- Event-wide, not per ticket type: somebody who wants to come wants to come,
-- and holding four separate queue positions for four ticket types would let one
-- person outrank three others.
CREATE TABLE IF NOT EXISTS public.waitlist_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        BIGINT      NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    user_id         BIGINT      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    -- Remembered so an offer can be steered at what they actually wanted, but
    -- never used to order the queue.
    preferred_ticket_type_id BIGINT REFERENCES public.ticket_types(id) ON DELETE SET NULL,
    quantity        INTEGER     NOT NULL DEFAULT 1 CHECK (quantity > 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Set when a seat is handed to them; they then have the event's normal
    -- purchase window to buy it.
    offered_at      TIMESTAMPTZ,
    offer_expires_at TIMESTAMPTZ,
    reservation_id  BIGINT      REFERENCES public.reservations(id) ON DELETE SET NULL,
    claimed_at      TIMESTAMPTZ,
    released_at     TIMESTAMPTZ,
    notified_at     TIMESTAMPTZ
);

-- One live place in the queue per person per event.
CREATE UNIQUE INDEX IF NOT EXISTS waitlist_active_key
    ON public.waitlist_entries (event_id, user_id)
    WHERE released_at IS NULL AND claimed_at IS NULL;

-- The queue itself: oldest first, skipping anyone already holding an offer.
CREATE INDEX IF NOT EXISTS waitlist_queue_idx
    ON public.waitlist_entries (event_id, created_at)
    WHERE released_at IS NULL AND claimed_at IS NULL AND offered_at IS NULL;

CREATE INDEX IF NOT EXISTS waitlist_offers_idx
    ON public.waitlist_entries (offer_expires_at)
    WHERE offered_at IS NOT NULL AND claimed_at IS NULL AND released_at IS NULL;

-- ------------------------------------------------------------- sponsors ----
-- "Tier" was invented by the mockup; EESoc does not grade sponsors, and the
-- live site shows a sector instead ("Quantitative Trading").
ALTER TABLE public.sponsors ADD COLUMN IF NOT EXISTS sector VARCHAR;
UPDATE public.sponsors SET sector = COALESCE(sector, tier) WHERE tier IS NOT NULL;
ALTER TABLE public.sponsors DROP COLUMN IF EXISTS tier;

-- ------------------------------------------------------------ committee ----
-- Ordering is ours to choose: ICU returns posts alphabetically, which puts the
-- President in the middle. `committee_profiles.sort_order` already exists; this
-- records when the roster was last pulled so the yearly sync can be skipped.
CREATE TABLE IF NOT EXISTS public.sync_settings (
    key        VARCHAR     PRIMARY KEY,
    value      VARCHAR     NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
