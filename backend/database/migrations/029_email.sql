-- Email: what people have asked to hear about, and what we have sent them.
--
-- Four things live here, plus the columns the outbound mail needs:
--
--   email_subscriptions  — standing opt-ins held against an account.
--   event_sale_alerts    — "tell me when THIS event goes on sale", which must
--                          work for somebody with no account at all.
--   email_campaigns      — the audit trail for anything sent in bulk.
--   unsubscribe tokens   — one per account, one per alert.
--
-- Everything sent in bulk must be unsubscribable without signing in, so the
-- token is the unit of identity in those links, never the user id.

-- ------------------------------------------------------------- preferences

-- Absent row means "the topic's own default", NOT "unsubscribed". The default
-- is declared in the API's topic registry (api/services/emailing.py) rather
-- than here, so changing a default does not need a migration and never
-- overwrites a choice somebody has actually made.
CREATE TABLE IF NOT EXISTS public.email_subscriptions (
    user_id    BIGINT      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    topic      VARCHAR     NOT NULL,
    subscribed BOOLEAN     NOT NULL DEFAULT true,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, topic)
);

-- The audience query reads by topic, not by user.
CREATE INDEX IF NOT EXISTS email_subscriptions_topic_idx
    ON public.email_subscriptions (topic) WHERE subscribed;

-- --------------------------------------------------------------- opt-outs

-- The address-level kill switch, deliberately NOT keyed on a user id.
--
-- Most of the people a newsletter reaches have no account: ICU members come
-- from the synced membership feed, and the departmental year lists are single
-- addresses with hundreds of readers behind them. An unsubscribe that only
-- works for account holders is not an unsubscribe, and minting an account for
-- everyone we mail would be a worse answer than storing the address.
--
-- `topic = '*'` means everything we send in bulk. Transactional mail — sign-in
-- codes, your own booking — is not suppressed by this and must not be: it is
-- the answer to something the person just did.
CREATE TABLE IF NOT EXISTS public.email_optouts (
    email      VARCHAR     NOT NULL,
    topic      VARCHAR     NOT NULL DEFAULT '*',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Free text, for "bounced", "asked by hand" and the like.
    reason     VARCHAR
);

-- Case-insensitive, because the same person types their address both ways and
-- an opt-out that misses on capitalisation is an opt-out that failed.
CREATE UNIQUE INDEX IF NOT EXISTS email_optouts_key
    ON public.email_optouts (lower(email), topic);

CREATE INDEX IF NOT EXISTS email_optouts_email_idx
    ON public.email_optouts (lower(email));


-- ------------------------------------------------------------ sale alerts

-- Keyed on the address, not the user: the whole point is that somebody who has
-- never signed in can ask to be told when tickets drop. A user id is attached
-- when we happen to know it, so the alert can be managed from the preferences
-- page too.
CREATE TABLE IF NOT EXISTS public.event_sale_alerts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT      NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    email        VARCHAR     NOT NULL,
    user_id      BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    token        CHAR(64)    NOT NULL
                 DEFAULT encode(sha256((random()::text || clock_timestamp()::text)::bytea), 'hex'),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    notified_at  TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ
);

-- One live alert per address per event. Partial, so cancelling and asking
-- again works rather than colliding with the dead row.
CREATE UNIQUE INDEX IF NOT EXISTS event_sale_alerts_key
    ON public.event_sale_alerts (event_id, lower(email))
    WHERE cancelled_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS event_sale_alerts_token_key
    ON public.event_sale_alerts (token);

-- The announcer's query: who still has to be told about this event.
CREATE INDEX IF NOT EXISTS event_sale_alerts_pending_idx
    ON public.event_sale_alerts (event_id)
    WHERE notified_at IS NULL AND cancelled_at IS NULL;

-- -------------------------------------------------------------- campaigns

-- Every bulk send is recorded before it starts, not after it finishes. A send
-- that dies half way through must leave evidence of who it already reached,
-- because the alternative is somebody pressing send again to "make sure".
CREATE TABLE IF NOT EXISTS public.email_campaigns (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject     VARCHAR     NOT NULL,
    heading     VARCHAR,
    body        TEXT        NOT NULL DEFAULT '',
    -- Audience keys as chosen in the admin screen, kept verbatim so the record
    -- still says who was targeted after the topic registry changes.
    audiences   JSONB       NOT NULL DEFAULT '[]'::jsonb,
    status      VARCHAR     NOT NULL DEFAULT 'draft'
                CHECK (status IN ('draft', 'sending', 'sent', 'failed')),
    recipients  INTEGER     NOT NULL DEFAULT 0,
    sent        INTEGER     NOT NULL DEFAULT 0,
    failed      INTEGER     NOT NULL DEFAULT 0,
    error       VARCHAR,
    created_by  BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at  TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS email_campaigns_recent_idx
    ON public.email_campaigns (created_at DESC);

-- --------------------------------------------------------- purchase links

-- Where to actually buy the thing. The Union's own product feed carries a URL
-- (union_products.url), which is preferred when it is there — but it is often
-- null for our centre, and a booking confirmation with no link to pay is the
-- single most useless email we could send. So the committee can set one by
-- hand, per ticket type or for the whole event.
ALTER TABLE public.events       ADD COLUMN IF NOT EXISTS purchase_url VARCHAR;
ALTER TABLE public.ticket_types ADD COLUMN IF NOT EXISTS purchase_url VARCHAR;

-- ------------------------------------------------------- on-sale announce

-- Set the moment the on-sale emails go out, so the announcer is idempotent:
-- it looks for published events whose sales_open_at has passed and whose
-- sales_announced_at is still null.
ALTER TABLE public.events ADD COLUMN IF NOT EXISTS sales_announced_at TIMESTAMPTZ;

-- Anything already on sale when this ships has, as far as anyone is
-- concerned, already been announced. Without this backfill the first run of
-- the announcer would mail the whole list about every event of the year.
UPDATE public.events
   SET sales_announced_at = NOW()
 WHERE sales_announced_at IS NULL
   AND sales_open_at IS NOT NULL
   AND sales_open_at <= NOW();

CREATE INDEX IF NOT EXISTS events_sales_announce_idx
    ON public.events (sales_open_at)
    WHERE published AND sales_announced_at IS NULL;

-- ---------------------------------------------------------- last chance

-- One nudge per hold, recorded so the daily pass cannot send it again. Not a
-- count: a second automated chase is nagging, and the committee already has a
-- manual "remind" button for the case that genuinely needs one.
ALTER TABLE public.reservations ADD COLUMN IF NOT EXISTS reminder_sent_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS reservations_reminder_idx
    ON public.reservations (expires_at)
    WHERE status = 'held' AND reminder_sent_at IS NULL;
