-- Per-recipient state for a bulk send.
--
-- A campaign row already records that a send started, but only as counts: a
-- pod killed mid-send knows it sent *some* messages and not which people got
-- one. That is what used to make a restart resend the whole audience or give
-- up on it, and pressing send again to "make sure" is how somebody gets the
-- newsletter twice and unsubscribes.
--
-- One row per recipient, claimed BEFORE the message goes out and confirmed
-- after: a killed pod's unconfirmed rows are re-claimable (once stale), while
-- a confirmed row is never mailed again. Claiming the sender lease
-- (job_leases, migration 035) means one sender at a time; this table means
-- that sender can be killed and replaced without losing its place.
CREATE TABLE IF NOT EXISTS public.campaign_recipients (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT      NOT NULL REFERENCES public.email_campaigns(id) ON DELETE CASCADE,
    email       VARCHAR     NOT NULL,
    -- pending → claimed → sent/failed. 'claimed' with an old claimed_at is a
    -- sender that died mid-batch; the claim endpoint re-takes those.
    status      VARCHAR     NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending', 'claimed', 'sent', 'failed')),
    claimed_at  TIMESTAMPTZ,
    sent_at     TIMESTAMPTZ,
    UNIQUE (campaign_id, email)
);

-- The sender's working query: everything still claimable for one campaign,
-- in the one index it walks a batch at a time.
CREATE INDEX IF NOT EXISTS campaign_recipients_work_idx
    ON public.campaign_recipients (campaign_id, status);
