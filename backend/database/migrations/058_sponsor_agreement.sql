-- The 2026-27 sponsorship agreement, made enforceable.
--
-- Until now the portal promised things the agreement does not say (a CV book,
-- a named prize, a newsletter slot for every listing) and could not represent
-- what it does say. Five changes, all additive:
--
--   1. sponsor_contacts — any number of contact points per sponsor, emails or
--      links, replacing the single CV address.
--   2. sponsor_terms — which clauses of the agreement each sponsor signed, with
--      an allowance where a clause is countable. The clause list itself lives in
--      code (api/services/agreement.py); a sponsor with no row for a clause gets
--      the standard package, which is the same for both fee tiers.
--   3. event_sponsorships — a sponsor now *registers interest* in an event
--      rather than claiming it outright, and the committee *links* the events a
--      sponsor actually has, recording which clause each one delivers.
--   4. sponsor_requests — a timing field, and a reply the sponsor can read.
--   5. sponsor_marketing — material a sponsor asks EESoc to share, counted
--      against a per-sponsor allowance.
--   6. sponsor_notes — questions and notes from a sponsor about anything, and
--      the committee's replies, threaded by what they are about.
--   7. job_listings.announced_at — whether members have been told of a role.
--
-- Numbered 058 rather than 035: 035-057 are reserved for the sections of the
-- in-progress plan, and the runner applies any unapplied number regardless of
-- order.

-- ---------------------------------------------------------------- 1. contacts
--
-- The cv_contact_* columns on sponsors are copied here and then left alone,
-- not dropped: a rollback to the previous image still reads them, and dropping
-- them would turn a rollback into an outage.

CREATE TABLE IF NOT EXISTS public.sponsor_contacts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    kind       VARCHAR     NOT NULL CHECK (kind IN ('email', 'link')),
    value      VARCHAR     NOT NULL,
    -- What the contact is for: "Send a CV", "Graduate recruitment".
    label      VARCHAR     NOT NULL DEFAULT '',
    -- "PDF only", "put EESoc in the subject line".
    note       VARCHAR     NOT NULL DEFAULT '',
    sort_order INTEGER     NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS sponsor_contacts_sponsor_idx
    ON public.sponsor_contacts (sponsor_id, sort_order, id);

INSERT INTO public.sponsor_contacts (sponsor_id, kind, value, label, note)
SELECT id, 'email', trim(cv_contact_email), 'Send a CV',
       concat_ws(' · ', NULLIF(trim(cv_contact_name), ''), NULLIF(trim(cv_contact_note), ''))
  FROM public.sponsors
 WHERE NULLIF(trim(cv_contact_email), '') IS NOT NULL;

-- ------------------------------------------------------------------- 2. terms
--
-- Clause keys are not constrained here: the catalogue is code, and a key the
-- code no longer knows is ignored rather than breaking the migration that
-- removes it.

CREATE TABLE IF NOT EXISTS public.sponsor_terms (
    sponsor_id BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    clause     VARCHAR     NOT NULL,
    agreed     BOOLEAN     NOT NULL DEFAULT true,
    -- Only meaningful for countable clauses: workshops, marketing sends, ...
    allowance  INTEGER     CHECK (allowance IS NULL OR allowance >= 0),
    note       TEXT        NOT NULL DEFAULT '',
    -- When a one-off clause was delivered, or a sponsor obligation met.
    done_at    TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    PRIMARY KEY (sponsor_id, clause)
);

-- ------------------------------------------------------- 3. event sponsorships
--
-- 'claimed' becomes 'interested'. The old check constraint is found by what it
-- constrains rather than by name: an inline CHECK's generated name is a
-- Postgres convention, and guessing wrong would fail this migration and keep
-- the adapter from starting.

DO $$
DECLARE
    con record;
BEGIN
    FOR con IN
        SELECT conname FROM pg_constraint
         WHERE conrelid = 'public.event_sponsorships'::regclass
           AND contype = 'c'
           AND pg_get_constraintdef(oid) ILIKE '%status%'
    LOOP
        EXECUTE format('ALTER TABLE public.event_sponsorships DROP CONSTRAINT %I', con.conname);
    END LOOP;
END $$;

UPDATE public.event_sponsorships SET status = 'interested' WHERE status = 'claimed';

ALTER TABLE public.event_sponsorships ALTER COLUMN status SET DEFAULT 'interested';
ALTER TABLE public.event_sponsorships
    ADD CONSTRAINT event_sponsorships_status_check
        CHECK (status IN ('interested', 'confirmed', 'declined'));

-- Which clause of the agreement a linked event delivers ('workshop',
-- 'seminar', ...). NULL is an event outside the package.
ALTER TABLE public.event_sponsorships ADD COLUMN IF NOT EXISTS clause VARCHAR;
ALTER TABLE public.event_sponsorships
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

CREATE INDEX IF NOT EXISTS event_sponsorships_event_idx
    ON public.event_sponsorships (event_id, status);

-- --------------------------------------------------------------- 4. requests

ALTER TABLE public.sponsor_requests ADD COLUMN IF NOT EXISTS timing VARCHAR;
-- The committee's answer, shown to the sponsor next to the request.
ALTER TABLE public.sponsor_requests
    ADD COLUMN IF NOT EXISTS response TEXT NOT NULL DEFAULT '';
ALTER TABLE public.sponsor_requests
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

-- -------------------------------------------------------------- 5. marketing

CREATE TABLE IF NOT EXISTS public.sponsor_marketing (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id     BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    -- The allowance is per academic year, so each request records its own.
    academic_year  VARCHAR     NOT NULL,
    subject        VARCHAR     NOT NULL,
    body           TEXT        NOT NULL DEFAULT '',
    -- URLs of files uploaded through the portal. Checked on the way in to be
    -- our own media, so nothing in a members' email is hosted by a third party.
    media          TEXT[]      NOT NULL DEFAULT '{}',
    -- Audience keys from the curated list in agreement.py, not the full admin
    -- set: a sponsor never picks "everyone with an account" or the test list.
    audiences      TEXT[]      NOT NULL DEFAULT '{}',
    channels       TEXT[]      NOT NULL DEFAULT '{email}',
    preferred_date DATE,
    status         VARCHAR     NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'shared', 'declined', 'withdrawn')),
    response       TEXT        NOT NULL DEFAULT '',
    campaign_id    BIGINT      REFERENCES public.email_campaigns(id) ON DELETE SET NULL,
    emailed_at     TIMESTAMPTZ,
    posted_at      TIMESTAMPTZ,
    created_by     BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    decided_by     BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS sponsor_marketing_sponsor_idx
    ON public.sponsor_marketing (sponsor_id, academic_year, status);
CREATE INDEX IF NOT EXISTS sponsor_marketing_pending_idx
    ON public.sponsor_marketing (created_at) WHERE status = 'pending';

-- ------------------------------------------------------------------ 6. notes
--
-- A thread is every note with the same (sponsor_id, topic). `topic` names what
-- the note is about — 'general', 'event:12', 'request:4', 'marketing:7',
-- 'listing:3', 'clause:workshop' — and `topic_label` keeps the title it had
-- when written, so a thread still reads sensibly after its event is deleted.

CREATE TABLE IF NOT EXISTS public.sponsor_notes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id     BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    topic          VARCHAR     NOT NULL DEFAULT 'general',
    topic_label    VARCHAR     NOT NULL DEFAULT '',
    body           TEXT        NOT NULL,
    -- Written by the committee (a reply) rather than by the sponsor.
    from_committee BOOLEAN     NOT NULL DEFAULT false,
    author_id      BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    -- When the other side read it: the committee for a sponsor's note, the
    -- sponsor for a reply. NULL is unread.
    read_at        TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS sponsor_notes_thread_idx
    ON public.sponsor_notes (sponsor_id, topic, created_at);
CREATE INDEX IF NOT EXISTS sponsor_notes_unread_idx
    ON public.sponsor_notes (created_at)
    WHERE read_at IS NULL AND NOT from_committee;

-- ------------------------------------------------------------ 7. listings
--
-- When a listing was included in a "new roles" email to the Jobs and
-- internships subscribers. NULL means members have not been told about it yet.
ALTER TABLE public.job_listings ADD COLUMN IF NOT EXISTS announced_at TIMESTAMPTZ;
