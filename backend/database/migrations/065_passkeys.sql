-- Passkeys: sign in with the device instead of an emailed code.
--
-- Expand-only: three new tables and one nullable column, so the previous image
-- keeps running against this schema mid-rollout and nothing existing reads any
-- of it.
--
-- Why at all: a sign-in code is an email, and email is the one thing this site
-- cannot make reliable. A sponsor's corporate filter quarantines it, and once a
-- year Imperial resets the webmaster mailbox password and nobody gets a code at
-- all. A passkey needs neither.

-- The opaque id an authenticator files this account's passkeys under
-- (WebAuthn's `user.id`). Random rather than the row id or the email: it is
-- handed to the authenticator, synced to the person's password manager, and
-- the spec asks that it carry nothing that identifies them. One per account so
-- a second registration on the same password manager replaces rather than
-- duplicates. Set lazily, on the first registration.
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS webauthn_handle VARCHAR;

CREATE UNIQUE INDEX IF NOT EXISTS users_webauthn_handle_key
    ON public.users (webauthn_handle) WHERE webauthn_handle IS NOT NULL;


-- A one-off link the committee gives somebody so they can save a passkey
-- without ever receiving a code: mostly sponsors whose mail server eats ours.
-- Whoever holds the link can put a passkey on the account, so it is treated
-- like a session token — only its hash is stored, it works once, and it
-- expires. `created_by` is kept because the api re-checks at redemption that
-- the person who made the link could still make it today.
CREATE TABLE IF NOT EXISTS public.passkey_links (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  CHAR(64)    NOT NULL UNIQUE,
    user_id     BIGINT      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_by  BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at  TIMESTAMPTZ NOT NULL,
    used_at     TIMESTAMPTZ,
    revoked_at  TIMESTAMPTZ,
    revoked_by  BIGINT      REFERENCES public.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS passkey_links_user_idx ON public.passkey_links (user_id);


-- One row per WebAuthn credential. The public key is all we ever hold — the
-- private half never leaves the person's device — so this table leaking signs
-- nobody in. Ids and keys are base64url text rather than BYTEA because that is
-- the form they travel in between the browser, the api and this service.
CREATE TABLE IF NOT EXISTS public.passkeys (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    credential_id VARCHAR     NOT NULL UNIQUE,
    public_key    TEXT        NOT NULL,
    -- The authenticator's use counter. Synced passkeys always report 0; a
    -- hardware key counts up, and going backwards means it was cloned.
    sign_count    BIGINT      NOT NULL DEFAULT 0,
    transports    VARCHAR[]   NOT NULL DEFAULT '{}',
    aaguid        VARCHAR,
    -- Synced to a password manager (multi_device) or stuck to one device.
    device_type   VARCHAR,
    backed_up     BOOLEAN     NOT NULL DEFAULT FALSE,
    -- "Chrome on macOS": enough for somebody to tell their passkeys apart.
    name          VARCHAR     NOT NULL DEFAULT '',
    -- Set when it was saved through a committee-made link, so the account page
    -- can say who made that link. NULL: they added it themselves.
    link_id       BIGINT      REFERENCES public.passkey_links(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_used_at  TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS passkeys_user_idx ON public.passkeys (user_id);


-- The single-use nonce each ceremony signs. In the database rather than in
-- process memory because the api runs more than one replica during a rollout,
-- and the "give me options" and "here is my answer" calls can land on
-- different pods. Deleted when used; expired rows are swept on every insert.
CREATE TABLE IF NOT EXISTS public.webauthn_challenges (
    challenge  VARCHAR     PRIMARY KEY,
    purpose    VARCHAR     NOT NULL CHECK (purpose IN ('register', 'authenticate')),
    -- Who a registration is for. NULL for sign-in: a discoverable passkey says
    -- whose it is only once it answers.
    user_id    BIGINT      REFERENCES public.users(id) ON DELETE CASCADE,
    -- The link a registration came through, so its answer can only be redeemed
    -- against the same link.
    link_id    BIGINT      REFERENCES public.passkey_links(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS webauthn_challenges_expires_idx
    ON public.webauthn_challenges (expires_at);
