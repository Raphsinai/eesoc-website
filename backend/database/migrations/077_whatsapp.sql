-- WhatsApp: the groups announcements are posted into, and every post made.
--
-- The site is linked to the society's WhatsApp number as one of its devices
-- (backend/whatsapp). It posts only into groups a committee member chose here,
-- and only when somebody sends or approves the announcement.
--
-- Expand-only: new tables, and one column with a default.

-- The groups chosen. Being in this table is being chosen. The name is a label
-- for screens where WhatsApp is not connected to ask; WhatsApp's own name for
-- the group is read fresh whenever it is.
CREATE TABLE IF NOT EXISTS public.whatsapp_groups (
    -- WhatsApp's id for the group, "…@g.us".
    jid      VARCHAR     PRIMARY KEY,
    name     VARCHAR     NOT NULL DEFAULT '',
    added_by BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    added_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- One row per post into one group, written BEFORE the post goes, as
-- campaign_recipients is for email: a pod that dies mid-post leaves a row
-- saying it may have gone, and a second pod's scheduler reaching the same
-- email finds the row and does not post it again. A group posted twice is the
-- failure that costs a society its members; one post lost is the right way
-- round.
CREATE TABLE IF NOT EXISTS public.whatsapp_posts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The email it went with, if any. Bare, no FK: as for a campaign's event,
    -- the record outlives what it was about.
    campaign_id BIGINT,
    jid         VARCHAR     NOT NULL,
    group_name  VARCHAR     NOT NULL DEFAULT '',
    body        TEXT        NOT NULL,
    status      VARCHAR     NOT NULL DEFAULT 'sending'
                CHECK (status IN ('sending', 'sent', 'failed')),
    -- WhatsApp's id for the message, once it has one.
    message_id  VARCHAR,
    error       VARCHAR,
    created_by  BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sent_at     TIMESTAMPTZ
);

-- The claim: one post per email per group, ever.
CREATE UNIQUE INDEX IF NOT EXISTS whatsapp_posts_campaign_key
    ON public.whatsapp_posts (campaign_id, jid)
    WHERE campaign_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS whatsapp_posts_recent_idx
    ON public.whatsapp_posts (created_at DESC);

-- Whether an email also goes to the chosen groups on WhatsApp when it is sent
-- — now, or at the time it was approved for.
ALTER TABLE public.email_campaigns
    ADD COLUMN IF NOT EXISTS whatsapp BOOLEAN NOT NULL DEFAULT false;
