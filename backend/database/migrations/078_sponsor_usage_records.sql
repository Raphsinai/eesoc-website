-- Package use the committee records by hand.
--
-- A countable clause's "used" was counted only from what passed through the
-- site: events linked to the sponsor, and marketing requests made in the
-- portal. A workshop agreed by email and held at the sponsor's office, or a
-- post shared straight to Instagram, used the allowance just the same and
-- could not be recorded. Each row here is one such use: it counts against the
-- clause for its academic year and shows in the sponsor's portal beside the
-- rest, so the number they see is one they can account for.
--
-- `title` is committee-written and shown to the sponsor; scrub.sql rewrites
-- any address in it on the staging copy.

CREATE TABLE IF NOT EXISTS public.sponsor_usage_records (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id    BIGINT      NOT NULL REFERENCES public.sponsors(id) ON DELETE CASCADE,
    -- A countable clause key from api/services/agreement.py. Not constrained
    -- here, for the same reason sponsor_terms.clause is not.
    clause        VARCHAR     NOT NULL,
    academic_year VARCHAR     NOT NULL,
    title         VARCHAR     NOT NULL,
    happened_on   DATE,
    created_by    BIGINT      REFERENCES public.users(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS sponsor_usage_records_sponsor_idx
    ON public.sponsor_usage_records (sponsor_id, academic_year, clause);
