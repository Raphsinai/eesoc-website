-- Member-submitted opportunities. A published listing is the result of a
-- committee review, never of a member-controlled field. The email draft is
-- created in the SAME transaction as approval so a retry or double-click
-- cannot approve without an announcement or create two announcements.
-- Expand-only: old API/database images simply ignore these new objects.
CREATE TABLE IF NOT EXISTS public.opportunities (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitted_by      BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    title             VARCHAR(180) NOT NULL,
    description       TEXT NOT NULL,
    links             JSONB NOT NULL DEFAULT '[]'::jsonb,
    contact_email     VARCHAR(254),
    contact_phone     VARCHAR(40),
    target_years      JSONB NOT NULL DEFAULT '[]'::jsonb,
    image_ids         BIGINT[] NOT NULL DEFAULT '{}'::bigint[],
    status            VARCHAR(16) NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending', 'approved', 'rejected')),
    review_notes      TEXT,
    reviewed_by       BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    reviewed_at       TIMESTAMPTZ,
    approved_at       TIMESTAMPTZ,
    email_campaign_id BIGINT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS opportunities_public_idx
    ON public.opportunities (approved_at DESC, id DESC) WHERE status = 'approved';
CREATE INDEX IF NOT EXISTS opportunities_review_idx
    ON public.opportunities (created_at DESC, id DESC) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS opportunities_owner_idx
    ON public.opportunities (submitted_by, created_at DESC);

-- Mirrors the event_id convention: campaign history must survive even if its
-- subject is removed. Resumable email needs only kind + saved body, but the id
-- makes the origin of the draft auditable.
ALTER TABLE public.email_campaigns
    ADD COLUMN IF NOT EXISTS opportunity_id BIGINT;
CREATE UNIQUE INDEX IF NOT EXISTS opportunity_one_campaign_idx
    ON public.email_campaigns (opportunity_id)
    WHERE kind = 'opportunity_announcement' AND opportunity_id IS NOT NULL;
