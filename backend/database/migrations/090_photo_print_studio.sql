-- Unlisted, individually shareable photo sets for EESoc's event print studio.
-- A draft never resolves through the public API, even if its token is known.
CREATE TABLE IF NOT EXISTS public.photo_sets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token        VARCHAR(64) NOT NULL UNIQUE,
    title        VARCHAR(100) NOT NULL,
    orientation  VARCHAR(10) NOT NULL DEFAULT 'portrait'
                 CHECK (orientation IN ('portrait', 'landscape')),
    status       VARCHAR(12) NOT NULL DEFAULT 'draft'
                 CHECK (status IN ('draft', 'published')),
    created_by   BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    published_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS photo_sets_recent_idx ON public.photo_sets (created_at DESC);

CREATE TABLE IF NOT EXISTS public.photo_set_images (
    set_id    BIGINT NOT NULL REFERENCES public.photo_sets(id) ON DELETE CASCADE,
    upload_id BIGINT NOT NULL UNIQUE REFERENCES public.uploads(id) ON DELETE RESTRICT,
    position  SMALLINT NOT NULL CHECK (position BETWEEN 0 AND 3),
    PRIMARY KEY (set_id, position)
);
