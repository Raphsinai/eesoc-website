-- Zero-downtime check fixture: a clean, expand-only migration.
--
-- Not applied to a database. New tables, new columns with a DEFAULT (or
-- nullable), and new indexes all apply without breaking a running replica, so
-- this must pass the check untouched. The NOT NULL inside CREATE TABLE is
-- deliberately present: it is fine there and must not be flagged, only the
-- NOT NULL on an ADD COLUMN without DEFAULT is a contract break.
CREATE TABLE IF NOT EXISTS public.campaign_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES public.email_campaigns(id) ON DELETE CASCADE,
    event_id    BIGINT REFERENCES public.events(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.email_campaigns
    ADD COLUMN IF NOT EXISTS kind VARCHAR DEFAULT 'newsletter';

CREATE INDEX IF NOT EXISTS campaign_events_campaign_idx
    ON public.campaign_events (campaign_id);